import fs from 'node:fs';
import path from 'node:path';
import {spawn} from 'node:child_process';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const require=createRequire(path.join(root,'apps/desktop/package.json'));
const {initialize}=require('./electron/publicConfig.cjs');
const configPath=process.env.LUMA_CONFIG||path.join(root,'luma.config.json');
const config=fs.existsSync(configPath)?JSON.parse(fs.readFileSync(configPath,'utf8')):{};
const dataDir=path.resolve(process.env.LUMA_DATA_DIR||path.join(root,'.local/userData'));
await initialize({dataDir,config,workspace:process.env.LUMA_WORKSPACE||config.workspace||path.join(root,'.local/workspace')});
if(!fs.existsSync(path.join(root,'apps/desktop/dist/index.html'))||!fs.existsSync(path.join(root,'apps/mobile/dist/index.html')))throw Error('Run npm run build first');
const exe=require('electron');
const extra=process.argv.slice(2);
const env={...process.env,XIAOWU_LOAD_DIST:'1',LUMA_CONFIG:configPath,LUMA_WORKSPACE:path.resolve(process.env.LUMA_WORKSPACE||config.workspace||path.join(root,'.local/workspace')),LUMA_LOCAL_MOBILE_PORT:process.env.LUMA_LOCAL_MOBILE_PORT||'8787'};
delete env.ELECTRON_RUN_AS_NODE;
const child=spawn(exe,[path.join(root,'apps/desktop'),`--user-data-dir=${dataDir}`,...extra],{env,stdio:'inherit',windowsHide:true});
let stopping=false;
for(const sig of ['SIGINT','SIGTERM'])process.on(sig,()=>{if(!stopping){stopping=true;child.kill(sig);}});
child.on('error',err=>{console.error(err.message);process.exitCode=1;});
child.on('exit',code=>{process.exitCode=code??1;});
