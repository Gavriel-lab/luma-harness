import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const args=process.argv.slice(2),option=name=>{const i=args.indexOf(name);return i<0?'':args[i+1]||'';};
const relay=option('--relay-host'),team=option('--team-domain'),aud=option('--aud'),email=option('--owner-email');
const gatewayName=option('--gateway-name')||'luma-harness',relayName=option('--relay-name')||'luma-harness-relay';
if(!/^[a-z0-9][a-z0-9.-]+$/.test(relay)||relay.endsWith('.invalid')||!/^https:\/\/[a-z0-9-]+\.cloudflareaccess\.com$/.test(team)||!/^[a-f0-9]{64}$/.test(aud)||!/^\S+@\S+\.\S+$/.test(email))throw Error('Usage: npm run configure:cloud -- --relay-host YOUR-RELAY.workers.dev --team-domain https://YOUR-TEAM.cloudflareaccess.com --aud ACCESS_APPLICATION_AUD --owner-email YOU@example.com');
if(!/^[a-z0-9-]+$/.test(gatewayName)||!/^[a-z0-9-]+$/.test(relayName))throw Error('Invalid Worker name');
const configPath=process.env.LUMA_CONFIG||path.join(root,'luma.config.json');
const config=fs.existsSync(configPath)?JSON.parse(fs.readFileSync(configPath,'utf8')):{};
const dataDir=path.resolve(process.env.LUMA_DATA_DIR||path.join(root,'.local/userData'));
const require=createRequire(import.meta.url),{initialize}=require('../apps/desktop/electron/publicConfig.cjs');
const {homeId}=await initialize({dataDir,config,workspace:config.workspace||path.join(root,'.local/workspace')});
const relayDir=path.join(dataDir,'luma-relay');fs.mkdirSync(relayDir,{recursive:true,mode:0o700});
const tokenFile=path.join(relayDir,'relay.token');
// Never rotate an existing pairing token implicitly.
if(!fs.existsSync(tokenFile))fs.writeFileSync(tokenFile,crypto.randomBytes(32).toString('hex'),{mode:0o600});
if(!/^[a-f0-9]{64}$/.test(fs.readFileSync(tokenFile,'utf8').trim()))throw Error('Existing pairing token is invalid; preserve it and inspect');
const write=(p,data)=>fs.writeFileSync(p,JSON.stringify(data,null,2)+'\n',{mode:0o600});
write(path.join(relayDir,'config.json'),{endpoint:`wss://${relay}/internal/relay`,homeId,tokenFile});
const gateway=JSON.parse(fs.readFileSync(path.join(root,'services/gateway/wrangler.example.json'),'utf8'));
Object.assign(gateway,{name:gatewayName});Object.assign(gateway.vars,{ACCESS_AUD:aud,ACCESS_TEAM_DOMAIN:team,OWNER_EMAIL:email,OWNER_NAME:config.ownerName||'使用者'});gateway.services[0].service=relayName;
write(path.join(root,'services/gateway/wrangler.json'),gateway);
const relayConfig=JSON.parse(fs.readFileSync(path.join(root,'services/relay/wrangler.example.json'),'utf8'));
relayConfig.name=relayName;relayConfig.vars.HOME_ID=homeId;write(path.join(root,'services/relay/wrangler.json'),relayConfig);
console.log('Local configuration created. The token stays in the protected data directory. See docs/DEPLOYMENT.md for Access protection, secret installation and deployment.');
